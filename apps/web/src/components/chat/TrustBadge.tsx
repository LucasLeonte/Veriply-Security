"use client";

import { useState } from "react";
import { Check, Zap, Clock } from "lucide-react";
import { TrustLevel } from "@/types/chat";

interface TrustBadgeProps {
    trustLevel: TrustLevel;
    confidenceScore?: number;
    updatedDate?: string;
}

export default function TrustBadge({
    trustLevel,
    confidenceScore,
    updatedDate,
}: TrustBadgeProps) {
    const [showTooltip, setShowTooltip] = useState(false);

    // Badge styles per trust level
    const badgeConfig = {
        verified: {
            background: "bg-green-100",
            text: "text-green-900",
            border: "border-green-200",
            icon: Check,
            label: "✓ Verified",
            ariaLabel: "Verified. This answer has been verified by a human expert.",
            tooltipText: "This answer has been verified by a human expert",
            additionalInfo: updatedDate ? `Updated: ${updatedDate}` : null,
        },
        ai_generated: {
            background: "bg-amber-100",
            text: "text-amber-900",
            border: "border-amber-200",
            icon: Zap,
            label: "AI Generated",
            ariaLabel: "AI generated. This answer was generated by artificial intelligence.",
            tooltipText: "This answer was generated by AI from our knowledge base",
            additionalInfo: confidenceScore
                ? `Confidence: ${Math.round(confidenceScore)}%`
                : null,
        },
        pending: {
            background: "bg-blue-100",
            text: "text-blue-900",
            border: "border-blue-200",
            icon: Clock,
            label: "Checking with the team",
            ariaLabel: "Pending. This answer is being verified by a human expert.",
            tooltipText: "We're verifying this answer. Check back soon.",
            additionalInfo: null,
        },
    };

    const config = badgeConfig[trustLevel];
    const Icon = config.icon;

    return (
        <div
            className="relative inline-flex"
            onMouseEnter={() => setShowTooltip(true)}
            onMouseLeave={() => setShowTooltip(false)}
        >
            <button
                className={`inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded text-xs font-medium border transition-colors ${config.background} ${config.text} ${config.border} hover:shadow-sm focus:outline-none focus:ring-2 focus:ring-offset-1`}
                aria-label={config.ariaLabel}
                role={trustLevel === "pending" ? "status" : undefined}
            >
                <Icon className="w-3.5 h-3.5" />
                <span>{config.label}</span>
            </button>

            {/* Tooltip */}
            {showTooltip && (
                <div
                    className="absolute bottom-full left-1/2 transform -translate-x-1/2 mb-2 px-3 py-2 bg-slate-900 text-white text-xs rounded shadow-lg whitespace-nowrap z-50 pointer-events-none"
                    role="tooltip"
                >
                    <div>{config.tooltipText}</div>
                    {config.additionalInfo && (
                        <div className="text-slate-300 text-xs mt-1">
                            {config.additionalInfo}
                        </div>
                    )}
                    {/* Tooltip arrow */}
                    <div className="absolute top-full left-1/2 transform -translate-x-1/2 w-0 h-0 border-l-4 border-r-4 border-t-4 border-l-transparent border-r-transparent border-t-slate-900" />
                </div>
            )}
        </div>
    );
}
