import { describe, it, expect } from "vitest";
import { render, screen, fireEvent } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import TrustBadge from "@/components/chat/TrustBadge";

describe("TrustBadge Component", () => {
    describe("Verified Badge", () => {
        it("renders verified badge with correct styling", () => {
            render(<TrustBadge trustLevel="verified" />);

            const badge = screen.getByRole("button");
            expect(badge).toHaveClass("bg-green-100");
            expect(badge).toHaveClass("text-green-900");
            expect(screen.getByText("✓ Verified")).toBeInTheDocument();
        });

        it("displays correct aria-label for verified badge", () => {
            render(<TrustBadge trustLevel="verified" />);

            const badge = screen.getByRole("button");
            expect(badge).toHaveAttribute(
                "aria-label",
                "Verified. This answer has been verified by a human expert."
            );
        });

        it("shows tooltip with verified message on hover", async () => {
            const { container } = render(
                <TrustBadge trustLevel="verified" />
            );

            const badge = screen.getByRole("button");
            
            // Use fireEvent for mouseenter
            fireEvent.mouseEnter(badge);

            // Verify tooltip is rendered
            const tooltip = container.querySelector('[role="tooltip"]');
            expect(tooltip).toBeInTheDocument();
            expect(tooltip?.textContent).toContain("This answer has been verified by a human expert");
        });

        it("displays update date in tooltip when provided", async () => {
            const { container } = render(
                <TrustBadge 
                    trustLevel="verified" 
                    updatedDate="Dec 18, 2025"
                />
            );

            const badge = screen.getByRole("button");
            fireEvent.mouseEnter(badge);

            const tooltip = container.querySelector('[role="tooltip"]');
            expect(tooltip?.textContent).toContain("Updated: Dec 18, 2025");
        });
    });

    describe("AI Generated Badge", () => {
        it("renders ai_generated badge with correct styling", () => {
            render(<TrustBadge trustLevel="ai_generated" />);

            const badge = screen.getByRole("button");
            expect(badge).toHaveClass("bg-amber-100");
            expect(badge).toHaveClass("text-amber-900");
            expect(screen.getByText("AI Generated")).toBeInTheDocument();
        });

        it("displays correct aria-label for ai_generated badge", () => {
            render(<TrustBadge trustLevel="ai_generated" />);

            const badge = screen.getByRole("button");
            expect(badge).toHaveAttribute(
                "aria-label",
                "AI generated. This answer was generated by artificial intelligence."
            );
        });

        it("shows confidence score in tooltip", () => {
            const { container } = render(
                <TrustBadge 
                    trustLevel="ai_generated" 
                    confidenceScore={85.5}
                />
            );

            const badge = screen.getByRole("button");
            fireEvent.mouseEnter(badge);

            const tooltip = container.querySelector('[role="tooltip"]');
            expect(tooltip?.textContent).toContain("Confidence: 86%");
        });
    });

    describe("Pending Badge", () => {
        it("renders pending badge with correct styling", () => {
            render(<TrustBadge trustLevel="pending" />);

            const badge = screen.getByRole("status");
            expect(badge).toHaveClass("bg-blue-100");
            expect(badge).toHaveClass("text-blue-900");
            expect(
                screen.getByText("Checking with the team")
            ).toBeInTheDocument();
        });

        it("has status role for pending badge (live region)", () => {
            render(<TrustBadge trustLevel="pending" />);

            const badge = screen.getByRole("status");
            expect(badge).toBeInTheDocument();
        });

        it("displays correct aria-label for pending badge", () => {
            render(<TrustBadge trustLevel="pending" />);

            const badge = screen.getByRole("status");
            expect(badge).toHaveAttribute(
                "aria-label",
                "Pending. This answer is being verified by a human expert."
            );
        });
    });

    describe("Accessibility", () => {
        it("has proper focus states for keyboard navigation", () => {
            const { container } = render(
                <TrustBadge trustLevel="verified" />
            );

            const badge = screen.getByRole("button");
            expect(badge).toHaveClass("focus:ring-2");
            expect(badge).toHaveClass("focus:outline-none");
        });

        it("colors meet WCAG AA contrast ratio requirements", () => {
            // Green: #DCFCE7 (bg) and #166534 (text) - High contrast
            // Amber: #FEF3C7 (bg) and #92400E (text) - High contrast
            // Blue: #DBEAFE (bg) and #1e3a8a (text) - High contrast
            
            render(<TrustBadge trustLevel="verified" />);
            const verifiedBadge = screen.getByRole("button");
            expect(verifiedBadge).toHaveClass("bg-green-100", "text-green-900");
        });
    });
});
